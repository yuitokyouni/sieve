def _load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


# ------------------------------------------------------------- examples ----

def test_examples_regenerate_byte_for_byte(tmp_path):
    """The mint tool is the only author of these files."""
    before = {p.name: p.read_bytes() for p in sorted(EXAMPLES.glob("*.json"))}
    subprocess.run([sys.executable,
                    str(REPO / "tools" / "mint_contract_examples.py")],
                   check=True, capture_output=True)
    after = {p.name: p.read_bytes() for p in sorted(EXAMPLES.glob("*.json"))}
    assert set(before) == set(after)
    drifted = [name for name in before if before[name] != after[name]]
    assert not drifted, (f"committed examples differ from a fresh mint: "
                         f"{drifted}. Run tools/mint_contract_examples.py.")


