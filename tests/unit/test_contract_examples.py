def test_harness_output_carries_no_threshold():
    """No threshold and no acceptance band reaches a v0.1 output. recovery_time
    and half_life are null with a reason attached, and the schema pins that
    with a const so one cannot be set by accident before Week 3."""
    output = _load(EXAMPLES / "ContHarnessOutput.example.json")["outputs"]
    shock = output["shock_response"]
    assert shock["recovery_time"] is None
    assert shock["half_life"] is None
    assert shock["recovery_time_note"] and shock["half_life_note"]
    schema = _load(SCHEMAS / "ContHarnessOutput.schema.json")
    response = schema["$defs"]["ShockResponse"]["properties"]
    assert response["recovery_time"]["const"] is None
    assert response["half_life"]["const"] is None


def test_every_estimate_reports_a_standard_error():
    """The uncertainty convention, enforced rather than described: an estimate
    that exists states what its +/- is."""
    output = _load(EXAMPLES / "ContHarnessOutput.example.json")["outputs"]
    for window in output["ofi_regression_by_window"]:
        for key, fit in window.items():
            if not isinstance(fit, dict):
                continue
            assert "n" in fit and "ddof" in fit, (window["window_index"], key)
            if fit.get("beta") is not None:
                assert fit["standard_error"] is not None
                assert "ddof" in fit["uncertainty"]


def test_primary_specification_has_an_intercept():
    """Ruling of 2026-08-20: primary = with intercept, to stay comparable with
    the estimating equation of Cont, Kukanov and Stoikov (2014); the
    no-intercept fit is kept beside it as the proportionality diagnostic, not
    instead of it."""
    output = _load(EXAMPLES / "ContHarnessOutput.example.json")["outputs"]
    windows = output["ofi_regression_by_window"]
    assert windows
    for window in windows:
        primary = window["primary_non_price_changing"]
        assert "alpha" in primary
        assert primary["ddof"] == 2
        secondary = window["secondary_non_price_changing_no_intercept"]
        assert secondary["ddof"] == 1


# ------------------------------------------------------ resolution map ----

def _pointer_exists(schema: dict, pointer: str) -> bool:
    """Walk a RunManifest-v2 JSON Pointer through the schema's structure."""
    node = schema
    for raw in [p for p in pointer.split("/") if p]:
        segment = re.sub(r"\[.*?\]$", "", raw)
        node = _resolve_ref(schema, node)
        if segment == "*":
            node = node.get("items") or node.get("additionalProperties")
            if not isinstance(node, dict):
                return False
            continue
        properties = _resolve_ref(schema, node).get("properties", {})
        if segment not in properties:
            extra = node.get("additionalProperties")
            if isinstance(extra, dict):
                node = extra
                continue
            return False
        node = properties[segment]
    return True


def _resolve_ref(root: dict, node: dict) -> dict:
    seen = 0
    while isinstance(node, dict) and "$ref" in node and seen < 8:
        target: dict = root
        for part in node["$ref"].lstrip("#/").split("/"):
            target = target[part]
        node = target
        seen += 1
    return node if isinstance(node, dict) else {}


def test_resolution_map_covers_exactly_the_calendar_items():
    conformance = _load(CONTRACT / "conformance_map.v1.json")
    refs = [item["item_ref"] for item in conformance["items"]]
    assert refs == EXPECTED_ITEM_REFS
    assert len(set(refs)) == len(refs)


def test_every_mapped_item_resolves_to_a_field_that_exists():
    """A resolution table whose pointers do not resolve resolves nothing."""
    conformance = _load(CONTRACT / "conformance_map.v1.json")
    schema = _load(SCHEMAS / "RunManifest.v2.schema.json")
    unresolved = [item["item_ref"] for item in conformance["items"]
                  if item["field_pointer"]
                  and not _pointer_exists(schema, item["field_pointer"])]
    assert not unresolved, unresolved


def test_every_calendar_item_is_a_fail_item():
    """Ruling of 2026-08-20: the contract profile's FAIL list is every 2.1
    item. There are no WARN items in this profile."""
    conformance = _load(CONTRACT / "conformance_map.v1.json")
    assert {item["profile_status"] for item in conformance["items"]} == {"FAIL"}


def test_manifest_example_declares_the_map_it_was_checked_against():
    manifest = _load(EXAMPLES / "RunManifest.v2.example.json")
    conformance = _load(CONTRACT / "conformance_map.v1.json")
